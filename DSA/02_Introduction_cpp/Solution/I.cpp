#include <bits/stdc++.h>
 
using namespace std;
 
 
 
int main() {
    long long a,b;
 
    cin>>a;
    cin>>b;
    cout<<a<<" + "<<b<<" = "<<a+b<<" "<<endl<<endl;
    cout<<a<<" - "<<b<<" = "<<a-b<<" "<<endl<<endl;
    cout<<a<<" * "<<b<<" = "<<a*b<<" "<<endl<<endl;
    cout<<a<<" / "<<b<<" = "<<a/b<<" "<<endl<<endl;
    cout<<a<<" % "<<b<<" = "<<a%b<<" ";
    return 0;
}
 
 